test('bounds transport origins, redirects, response bytes and sanitizes provider failures', async () => {
  for (const invalid of ['https://outside.example/secret', 'https://user:pass@auth.example/scan', 'https://auth.example/scan#token', 'http://auth.example/scan']) {
    let calls = 0;
    const auth = createDesktopAuthTransport(plainOptions(async () => { calls++; return response(challengeData({ chk_wait_scan: invalid })); }));
    try {
      await assert.rejects(auth.requestChallenge(), { code: 'invalid-poll-origin' });
      assert.equal(calls, 1);
    } finally { auth.close(); }
  }
  for (const [fetch, expected, extra] of [
    [async () => { throw Error('secret-url-and-cookie'); }, 'request-failed', {}],
    [async () => new Response('x'.repeat(1025)), 'response-limit', { maxResponseBytes: 1024 }],
    [async () => { const reply = response(challengeData()); Object.defineProperty(reply, 'redirected', { value: true }); return reply; }, 'invalid-response', {}],
    [async () => new Response(JSON.stringify({ error_code: 77, error_message: 'secret-url-and-cookie' })), 'provider-rejected', {}],
  ]) {
    const auth = createDesktopAuthTransport(plainOptions(fetch, extra));
    try {
      await assert.rejects(auth.requestChallenge(), (error) => {
        assert.ok(error instanceof DesktopAuthError);
        assert.equal(error.code, expected);
        assert.equal(JSON.stringify(error).includes('secret-url-and-cookie'), false);
        assert.equal(String(error).includes('secret-url-and-cookie'), false);
        return true;
      });
    } finally { auth.close(); }
  }
});

