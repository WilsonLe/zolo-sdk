import assert from 'node:assert/strict';
import { createCipheriv, createDecipheriv, createHash } from 'node:crypto';
import test from 'node:test';
import { createDesktopAuthTransport, DesktopAuthError } from '../dist/desktop-auth.js';
import { createTrustedDevicePairing } from '../dist/trusted-device-pairing.js';
import { ed25519Pkcs8, importE2eePrivateBytes } from '../dist/e2ee-web-identity.js';
import { desktopAuthFixture as oracle } from './fixtures/desktop-auth.mjs';
import { trustedDevicePairingFixture as pairingFixture } from './fixtures/trusted-device-pairing.mjs';

const origin = 'https://auth.example';
const scanUrl = `${origin}/scan?signed=%2fA%2b&n=1`;
const approvalUrl = `${origin}/approve?signed=%2fA%2b&n=1`;
const response = (data, code = 0, headers) => new Response(JSON.stringify({ error_code: code, data }), { headers });
const challengeData = (extra = {}) => ({
  token_id: pairingFixture.token, qr_timeout: 60, qr_retry: 3,
  chk_wait_scan: scanUrl, chk_wait_cfirm: approvalUrl, ...extra,
});
const config = (encrypted = true, self = 1, trusted = 1) => ({
  setttings: { authen: { encryption: { enable: encrypted }, trusted_device: { self_g: self, qr_format_trust_device: trusted } } },
});
const options = (fetch, extra = {}) => ({
  authOrigin: origin, imei: 'fixture-imei', computerName: 'Fixture Mac', language: 'en',
  now: () => pairingFixture.timestamp, fetch, ...extra,
});
const plainOptions = (fetch, extra = {}) => options(fetch, { encryption: 'plain', selfGeneratedQr: true, trustedDeviceQr: true, ...extra });

function signature(operation, fields) {
  return createHash('md5').update(`zsecure${operation}${Object.keys(fields).sort().map((key) => fields[key]).join('')}`).digest('hex');
}
function requestKey(params) {
  const half = (value, at) => [...value].filter((_, index) => index % 2 === at);
  return Buffer.from(
    half(createHash('md5').update(params.get('zcid_ext')).digest('hex').toUpperCase(), 0).slice(0, 8).join('')
    + half(params.get('zcid'), 0).slice(0, 12).join('')
    + half(params.get('zcid'), 1).reverse().slice(0, 12).join(''),
  );
}
function encryptedResponse(data, key, code = 0) {
  const cipher = createCipheriv('aes-256-cbc', key, Buffer.alloc(16));
  const body = JSON.stringify({ error_code: code, data });
  return response(encodeURIComponent(Buffer.concat([cipher.update(body), cipher.final()]).toString('base64')));
}

test('matches the installed cipher oracle and completes synthetic signed trusted-device pairing', async () => {
  const seen = [];
  let session;
  const auth = createDesktopAuthTransport(options(async (raw, init) => {
    seen.push(raw);
    assert.equal(init.method, 'GET');
    assert.equal(init.redirect, 'error');
    assert.equal(init.credentials, 'omit');
    const url = new URL(raw);
    if (url.pathname.endsWith('getServerInfo')) {
      const fields = Object.fromEntries(url.searchParams);
      delete fields.signkey;
      assert.equal(url.searchParams.get('signkey'), signature('getserverinfo', fields));
      assert.deepEqual(fields, { imei: 'fixture-imei', type: '30', client_version: '695', computer_name: 'Fixture Mac', sp_mtn: '-1', bkt: '-1' });
      assert.equal(init.headers, undefined);
      return response(config(), 0, { 'set-cookie': 'preauth=synthetic; Secure; HttpOnly; Path=/' });
    }
    assert.equal(init.headers.Cookie, 'preauth=synthetic');
    if (url.pathname.endsWith('reqqr')) {
      const params = url.searchParams;
      assert.equal(params.get('zcid'), oracle.params.zcid);
      assert.equal(params.get('enc_ver'), 'v2');
      assert.match(params.get('zcid_ext'), /^[0-9a-f]{12}$/);
      const fields = Object.fromEntries(params);
      delete fields.signkey;
      assert.equal(params.get('signkey'), signature('reqqr', fields));
      const key = requestKey(params);
      const cipher = createDecipheriv('aes-256-cbc', key, Buffer.alloc(16));
      const plain = Buffer.concat([cipher.update(Buffer.from(params.get('params'), 'base64')), cipher.final()]);
      assert.deepEqual(JSON.parse(plain), oracle.input);
      // Fixed bytes generated by the installed implementation independently of this transport.
      const fixtureCipher = createDecipheriv('aes-256-cbc', Buffer.from(oracle.requestKey), Buffer.alloc(16));
      assert.deepEqual(JSON.parse(Buffer.concat([fixtureCipher.update(Buffer.from(oracle.params.params, 'base64')), fixtureCipher.final()])), oracle.input);
      return encryptedResponse(challengeData(), key);
    }
    if (url.pathname === '/scan') {
      assert.equal(raw, `${scanUrl}&lang=en`);
      return response({ display_name: 'Synthetic Phone', link_data: pairingFixture.scan });
    }
    assert.equal(raw.startsWith(`${approvalUrl}&encLinkingMetaData=`), true);
    assert.equal(url.searchParams.get('encPK'), pairingFixture.proof.encPK);
    assert.equal(url.searchParams.get('encAccountSign'), pairingFixture.proof.encAccountSign);
    session = pairingFixture.approved;
    return response(session);
  }));
  const pairing = createTrustedDevicePairing({
    identitySigningKey: importE2eePrivateBytes(ed25519Pkcs8, Buffer.alloc(32, 2)), linkingSecret: Buffer.alloc(32, 123),
  });
  try {
    assert.deepEqual(await auth.getServerInfo(), { encryptionEnabled: true, selfGeneratedQr: true, trustedDeviceQr: true });
    const qr = await auth.requestChallenge();
    assert.deepEqual(qr.qr, { kind: 'trusted-device', token: pairingFixture.token });
    assert.equal(pairing.createQr(qr.qr.token, pairingFixture.timestamp), pairingFixture.desktopQr);
    const scan = await auth.pollScan(qr);
    assert.equal(scan.kind, 'scanned');
    await assert.rejects(auth.pollApproval(qr), { code: 'invalid-state' });
    const confirmed = pairing.prepareConfirmation(scan.linkData);
    const approved = await auth.pollApproval(qr, confirmed);
    assert.equal(approved.kind, 'approved');
    assert.deepEqual(approved.data, session);
    assert.equal(approved.cookies[0].key, 'preauth');
    assert.equal(approved.cookies[0].httpOnly, true);
    assert.equal(pairing.verifyApproval(approved.data, pairingFixture.timestamp).linkId, '9007199254740993');
    await assert.rejects(auth.pollApproval(qr, confirmed), { code: 'invalid-state' });
    assert.equal(seen.length, 4);
  } finally { auth.close(); pairing.close(); }
});

test('derives plain encryption and image/text QR presentation from provider config', async () => {
  for (const [self, trusted, data, expected] of [
    [0, 1, { base64_qr: 'aW1hZ2U=' }, { kind: 'png', base64: 'aW1hZ2U=' }],
    [1, 0, { qr_cnt: 'ordinary-qr-text' }, { kind: 'text', text: 'ordinary-qr-text' }],
  ]) {
    const auth = createDesktopAuthTransport(options(async (raw) => {
      const url = new URL(raw);
      if (url.pathname.endsWith('getServerInfo')) return response(config(0, self, trusted));
      if (url.pathname.endsWith('reqqr')) {
        assert.equal(url.searchParams.get('params'), null);
        assert.equal(url.searchParams.get('self_g'), String(self));
        assert.equal(url.searchParams.get('qr_form'), String(trusted));
        return response(challengeData(data));
      }
      return response(url.pathname === '/scan' ? { display_name: 'Synthetic Phone' } : { uid: 'synthetic' });
    }));
    try {
      const challenge = await auth.requestChallenge();
      assert.deepEqual(challenge.qr, expected);
      assert.equal(challenge.trustedDeviceQr, false);
      await auth.pollScan(challenge);
      assert.equal((await auth.pollApproval(challenge)).kind, 'approved');
    } finally { auth.close(); }
  }
});

test('retries encrypted reqqr once in plain mode after provider code 19000', async () => {
  let calls = 0;
  const auth = createDesktopAuthTransport(plainOptions(async (raw) => {
    const params = new URL(raw).searchParams;
    if (++calls === 1) { assert.ok(params.get('params')); return response(null, 19000); }
    assert.equal(params.get('params'), null);
    assert.equal(params.get('imei'), 'fixture-imei');
    return response(challengeData());
  }, { encryption: 'v2' }));
  try { assert.equal((await auth.requestChallenge()).qr.kind, 'trusted-device'); assert.equal(calls, 2); }
  finally { auth.close(); }
});

test('treats encrypted inner reqqr code 19000 as a refusal without a plain retry', async () => {
  const requests = [];
  const auth = createDesktopAuthTransport(plainOptions(async (raw) => {
    const url = new URL(raw);
    requests.push(url);
    assert.equal(url.pathname, '/api/login/reqqr');
    // A second plain response would succeed, exposing an unintended fallback.
    if (requests.length > 1) return response(challengeData());
    assert.ok(url.searchParams.get('params'));
    return encryptedResponse(null, requestKey(url.searchParams), 19000);
  }, { encryption: 'v2' }));
  let refusal;
  try {
    try { await auth.requestChallenge(); } catch (error) { refusal = error; }
    assert.equal(requests.length, 1, 'an inner refusal must not submit a second plain QR request');
    assert.ok(refusal instanceof DesktopAuthError);
    assert.equal(refusal.code, 'provider-rejected');
    assert.equal(refusal.providerCode, 19000);
  } finally { auth.close(); }
});

test('maps replacement QR priority and rejects stale or cloned challenge handles', async () => {
  for (const [replacement, expected] of [
    [{ ntk: 'new-token', qr_cnt: 'ignored' }, { kind: 'trusted-device', token: 'new-token' }],
    [{ ntk: '', qr_cnt: 'ordinary-replacement', base64_qr: 'aW1hZ2U=' }, { kind: 'text', text: 'ordinary-replacement' }],
    [{ ntk: 'new-token', base64_qr: 'aW1hZ2U=' }, { kind: 'png', base64: 'aW1hZ2U=' }],
  ]) {
    const auth = createDesktopAuthTransport(plainOptions(async (raw) => new URL(raw).pathname.endsWith('reqqr')
      ? response(challengeData()) : response(challengeData(replacement), -20)));
    try {
      const first = await auth.requestChallenge();
      await assert.rejects(auth.pollScan({ ...first }), { code: 'invalid-state' });
      const next = await auth.pollScan(first);
      assert.equal(next.kind, 'replacement');
      assert.equal(next.challenge.replacement, true);
      assert.deepEqual(next.challenge.qr, expected);
      await assert.rejects(auth.pollScan(first), { code: 'invalid-state' });
    } finally { auth.close(); }
  }
});

