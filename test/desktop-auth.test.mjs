test('enforces cancellation, deadlines and lifetime even with a transport that ignores abort', async () => {
  for (const [extra, expected] of [
    [{ requestTimeoutMs: 5 }, 'timed-out'], [{ maxLifetimeMs: 5 }, 'expired'],
  ]) {
    const hold = setTimeout(() => {}, 100);
    const auth = createDesktopAuthTransport(plainOptions(async () => new Promise(() => {}), extra));
    try { await assert.rejects(auth.requestChallenge(), { code: expected }); }
    finally { clearTimeout(hold); auth.close(); }
  }
  const controller = new AbortController();
  const auth = createDesktopAuthTransport(plainOptions(async () => { controller.abort('secret-abort-reason'); return response(challengeData()); }, { signal: controller.signal }));
  await assert.rejects(auth.requestChallenge(), { code: 'aborted' });
  await assert.rejects(auth.getServerInfo(), { code: 'aborted' });
  auth.close();
});

test('rejects a close interleaved with final response reading', async () => {
  let auth;
  let pulls = 0;
  auth = createDesktopAuthTransport(plainOptions(async () => new Response(new ReadableStream({
    pull(controller) {
      if (++pulls === 1) controller.enqueue(Buffer.from(JSON.stringify({ error_code: 0, data: challengeData() })));
      else { controller.close(); queueMicrotask(() => auth.close()); }
    },
  }), { headers: { 'set-cookie': 'private=fixture; Secure; Path=/' } })));
  await assert.rejects(auth.requestChallenge(), { code: 'closed' });
  await assert.rejects(auth.getServerInfo(), { code: 'closed' });
});
